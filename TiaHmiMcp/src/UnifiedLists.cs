// Textlisten und globale Skriptmodule von WinCC Unified. Openness V21 bietet dafuer nur Export und Import als YAML (und .hmi.js), kein Anlegen.
// Das Format stammt aus Exporten von TIA V21 (live 07.11.2026):
//   <name>.hmi.yml und <name>.TextLibrary.hmi.yml fuer Textlisten, <modul>.hmi.yml und <modul>.hmi.js fuer Skriptmodule.
// Skriptmodule lassen sich ueber Openness nicht loeschen.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Siemens.Engineering;
using Siemens.Engineering.HmiUnified;
using Siemens.Engineering.HmiUnified.Scripts;
using Siemens.Engineering.HmiUnified.TextGraphicList;

namespace Herzog.TiaHmi
{
    internal sealed class UnifiedLists
    {
        private const string ScriptMarker = "/*<auto-generated>\n***End of Global definition area***\nChanges to this comment may cause incorrect behavior during document based import.\n</auto-generated>*/\n";
        private readonly Options _options;
        private readonly Journal _journal;

        public UnifiedLists(Options options, Journal journal)
        {
            _options = options;
            _journal = journal;
        }

        private string NewDir(string kind)
        {
            string dir = Path.Combine(_options.WorkDir, kind, DateTime.Now.ToString("yyyyMMdd-HHmmss-fff"));
            Directory.CreateDirectory(dir);
            return dir;
        }

        private static string Yaml(string s)
        {
            return "'" + (s ?? "").Replace("'", "''") + "'";
        }

        private static string Raw(string s)
        {
            return s.Replace("\r\n", "\n");
        }

        // ---------- Textlisten ----------

        public Dictionary<string, object> TextList(Project project, HmiDevice device, Dictionary<string, object> args)
        {
            HmiSoftware sw = device.UnifiedSoftware;
            string aktion = UnifiedEditor.Required(args, "aktion");
            var result = new Dictionary<string, object> { { "projekt", project.Name }, { "hmi", device.SoftwareName } };
            List<string> names = sw.HmiTextLists.Cast<HmiTextList>().Select(t => t.Name).ToList();
            if (aktion == "liste")
            {
                result["textlisten"] = names;
                return result;
            }
            if (aktion == "lesen")
            {
                string dir = NewDir("textlisten");
                sw.HmiTextLists.Export(new DirectoryInfo(dir), "Alle");
                result["dateien"] = Directory.GetFiles(dir).ToList();
                result["inhalt"] = string.Join("\n", Directory.GetFiles(dir, "*.yml").OrderBy(f => f).Select(f => File.ReadAllText(f, Encoding.UTF8)));
                return result;
            }
            string name = UnifiedEditor.Required(args, "name");
            bool exists = names.Any(n => string.Equals(n, name, StringComparison.OrdinalIgnoreCase));
            string path = UnifiedEditor.ProjectPath(project);
            switch (aktion)
            {
                case "schreiben":
                    {
                        var entries = UnifiedEditor.Member(args, "eintraege") as object[];
                        if (entries == null || entries.Length == 0) throw new ToolException("'eintraege' fehlt: [{wert: 0, text: \"Hand\"}] oder {von, bis, texte: {\"de-DE\": ...}}.");
                        string backup = exists ? BackupTextLists(sw) : null;
                        WriteTextList(project, sw, name, entries);
                        var step = exists
                            ? Journal.Step("textliste_zurueck", "hmi", device.SoftwareName, "verzeichnis", backup, "datei", "Alle")
                            : Journal.Step("textliste_loeschen", "hmi", device.SoftwareName, "name", name);
                        result["undo"] = _journal.Add(path, "hmi_unified_textliste", "Textliste " + name + (exists ? " geaendert" : " angelegt"), device.SoftwareName, new List<Dictionary<string, object>> { step });
                        result["angewendet"] = true;
                        result["ergebnis"] = (exists ? "Geaendert" : "Angelegt") + ", nicht gespeichert. Anbinden: symbolfeld mit eigenschaften ResourceList oder Dynamisierung. Rueckgaengig mit hmi_undo.";
                        if (!exists)
                        {
                            // Wurde eine Liste in TIA umbenannt, legte schreiben mit dem alten Namen still eine zweite an (Feldbefund 13.11.2026, Punkt 40).
                            List<string> similar = Similar(sw, name, entries.Length);
                            result["neuAngelegt"] = true;
                            result["hinweis"] = "Textliste '" + name + "' gab es nicht, sie wurde NEU angelegt." +
                                (similar.Count > 0 ? " Aehnlich und vielleicht gemeint (umbenannt?): " + string.Join(", ", similar) + ". Dann mit hmi_undo zuruecknehmen und den richtigen Namen nehmen." : "");
                        }
                        return result;
                    }
                case "loeschen":
                    {
                        if (!exists) throw new ToolException("Textliste '" + name + "' gibt es nicht.");
                        string backup = BackupTextLists(sw);
                        sw.HmiTextLists.Find(name).Delete();
                        result["undo"] = _journal.Add(path, "hmi_unified_textliste", "Textliste " + name + " geloescht", device.SoftwareName,
                            new List<Dictionary<string, object>> { Journal.Step("textliste_zurueck", "hmi", device.SoftwareName, "verzeichnis", backup, "datei", "Alle") });
                        result["angewendet"] = true;
                        result["ergebnis"] = "Geloescht, nicht gespeichert. Rueckgaengig mit hmi_undo.";
                        return result;
                    }
                default: throw new ToolException("aktion '" + aktion + "' gibt es nicht. Erlaubt: liste, lesen, schreiben, loeschen.");
            }
        }

        // Andere Listen mit aehnlichem Namen oder gleich vielen Eintraegen.
        private static List<string> Similar(HmiSoftware sw, string name, int entryCount)
        {
            var result = new List<string>();
            string a = name.ToLowerInvariant();
            foreach (HmiTextList t in sw.HmiTextLists)
            {
                if (string.Equals(t.Name, name, StringComparison.OrdinalIgnoreCase)) continue;
                string b = t.Name.ToLowerInvariant();
                int prefix = 0;
                while (prefix < a.Length && prefix < b.Length && a[prefix] == b[prefix]) prefix++;
                bool nameLike = a.Contains(b) || b.Contains(a) || prefix >= Math.Min(5, Math.Min(a.Length, b.Length));
                int count = -1;
                try
                {
                    object entries = UnifiedProps.Member(t, "Entries");
                    if (entries is System.Collections.ICollection) count = ((System.Collections.ICollection)entries).Count;
                    else if (entries != null) count = Convert.ToInt32(UnifiedProps.Member(entries, "Count"), CultureInfo.InvariantCulture);
                }
                catch (Exception)
                {
                }
                if (nameLike || (count == entryCount && entryCount >= 3)) result.Add(t.Name + (count >= 0 ? " (" + count + " Eintraege)" : ""));
            }
            return result.Take(5).ToList();
        }

        private string BackupTextLists(HmiSoftware sw)
        {
            string dir = NewDir("sicherung");
            sw.HmiTextLists.Export(new DirectoryInfo(dir), "Alle");
            return dir;
        }

        private void WriteTextList(Project project, HmiSoftware sw, string name, object[] entries)
        {
            var languages = new Dictionary<string, Language>(StringComparer.OrdinalIgnoreCase);
            string editing;
            UnifiedEditor.FillLanguages(project, languages, out editing);
            var rows = new List<Dictionary<string, string>>();
            var used = new List<string>();
            var numbers = new List<KeyValuePair<long, long>>();
            foreach (object o in entries)
            {
                var d = o as Dictionary<string, object>;
                if (d == null) throw new ToolException("Jeder Eintrag muss ein Objekt sein.");
                object wert = UnifiedEditor.Member(d, "wert");
                object von = UnifiedEditor.Member(d, "von") ?? wert;
                object bis = UnifiedEditor.Member(d, "bis") ?? von;
                if (von == null) throw new ToolException("Eintrag ohne 'wert' oder 'von'.");
                numbers.Add(new KeyValuePair<long, long>(Convert.ToInt64(von, CultureInfo.InvariantCulture), Convert.ToInt64(bis, CultureInfo.InvariantCulture)));
                var texts = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                var map = UnifiedEditor.Member(d, "texte") as Dictionary<string, object>;
                if (map != null)
                {
                    foreach (var kv in map)
                    {
                        if (!languages.ContainsKey(kv.Key)) throw new ToolException("Sprache '" + kv.Key + "' ist keine aktive Projektsprache. Vorhanden: " + string.Join(", ", languages.Keys) + ".");
                        texts[kv.Key] = Convert.ToString(kv.Value, CultureInfo.InvariantCulture);
                    }
                }
                string text = UnifiedEditor.Text(d, "text");
                if (text != null) texts[editing] = text;
                if (texts.Count == 0) throw new ToolException("Eintrag ohne 'text' oder 'texte'.");
                foreach (string c in texts.Keys) if (!used.Contains(c, StringComparer.OrdinalIgnoreCase)) used.Add(c);
                rows.Add(texts);
            }
            string library = name + "_Texte";
            var list = new StringBuilder("#Version: 2.0\n\nTextListContainers:\n  DeviceTextList:\n    ResourceListType: TextList\n    ResourceLists:\n      " + name + ":\n        Entries:\n");
            var lib = new StringBuilder("#Version: 2.0\n\nTextLibraries:\n  " + library + ":\n    Type: Text\n    Languages:\n");
            foreach (string c in used) lib.Append("    - " + c + "\n");
            lib.Append("    DefaultLanguage: " + (used.Contains(editing, StringComparer.OrdinalIgnoreCase) ? editing : used[0]) + "\n    Entries:\n");
            for (int i = 0; i < rows.Count; i++)
            {
                list.Append("          Text_list_entry_" + i + ":\n");
                if (numbers[i].Key == numbers[i].Value) list.Append("            Value: " + numbers[i].Key + "\n");
                list.Append("            FromValue: " + numbers[i].Key + "\n            ToValue: " + numbers[i].Value + "\n            Text: " + library + ".Text_" + i + "\n");
                lib.Append("      Text_" + i + ":\n        Text:\n");
                foreach (string c in used)
                {
                    string t;
                    lib.Append("        - " + Yaml(rows[i].TryGetValue(c, out t) ? t : "") + "\n");
                }
            }
            string dir = NewDir("textlisten");
            var utf8 = new UTF8Encoding(false);
            File.WriteAllText(Path.Combine(dir, name + ".hmi.yml"), list.ToString(), utf8);
            File.WriteAllText(Path.Combine(dir, name + ".TextLibrary.hmi.yml"), lib.ToString(), utf8);
            bool ok;
            try
            {
                ok = sw.HmiTextLists.Import(new DirectoryInfo(dir), name);
            }
            catch (Exception ex)
            {
                throw new ToolException("TIA lehnt die Textliste ab: " + UnifiedProps.Innermost(ex));
            }
            if (!ok || sw.HmiTextLists.Find(name) == null) throw new ToolException("TIA hat die Textliste nicht importiert. Dateien: " + dir);
        }

        // ---------- Skriptmodule ----------

        public Dictionary<string, object> Script(Project project, HmiDevice device, Dictionary<string, object> args)
        {
            HmiSoftware sw = device.UnifiedSoftware;
            string aktion = UnifiedEditor.Required(args, "aktion");
            var result = new Dictionary<string, object> { { "projekt", project.Name }, { "hmi", device.SoftwareName } };
            List<string> names = sw.Scripts.Cast<HmiScriptModule>().Select(m => m.Name).ToList();
            if (aktion == "liste")
            {
                result["module"] = names;
                return result;
            }
            string name = UnifiedEditor.Required(args, "modul");
            bool exists = names.Any(n => string.Equals(n, name, StringComparison.OrdinalIgnoreCase));
            if (aktion == "lesen")
            {
                if (!exists) throw new ToolException("Skriptmodul '" + name + "' gibt es nicht. Vorhanden: " + string.Join(", ", names) + ".");
                string dir = ExportScripts(sw);
                result["datei"] = Path.Combine(dir, name + ".hmi.js");
                result["code"] = File.ReadAllText(Path.Combine(dir, name + ".hmi.js"), Encoding.UTF8);
                return result;
            }
            if (aktion != "schreiben") throw new ToolException("aktion '" + aktion + "' gibt es nicht. Erlaubt: liste, lesen, schreiben. Openness kann Skriptmodule nicht loeschen.");
            string code = UnifiedEditor.Required(args, "code");
            string global = UnifiedEditor.Text(args, "global") ?? "";
            string backup = exists ? ExportScripts(sw) : null;
            ImportScript(sw, name, Raw(global), Raw(code));
            result["undo"] = _journal.Add(UnifiedEditor.ProjectPath(project), "hmi_unified_skript", "Skriptmodul " + name + (exists ? " geaendert" : " angelegt"), device.SoftwareName,
                new List<Dictionary<string, object>> { Journal.Step("skript_zurueck", "hmi", device.SoftwareName, "modul", name, "verzeichnis", backup) });
            result["angewendet"] = true;
            result["ergebnis"] = (exists ? "Geaendert" : "Angelegt") + ", nicht gespeichert. Pruefen: hmi_uebersetzen. Aufruf aus Bildern: " + name + ".Funktion(...)." + (exists ? "" : " Ein neues Modul bleibt nach hmi_undo leer stehen, Openness kann es nicht loeschen.");
            return result;
        }

        private string ExportScripts(HmiSoftware sw)
        {
            string dir = NewDir("skripte");
            sw.Scripts.Export(new DirectoryInfo(dir));
            return dir;
        }

        private void ImportScript(HmiSoftware sw, string name, string global, string code)
        {
            string dir = NewDir("skripte");
            var utf8 = new UTF8Encoding(false);
            string body = (global.Length > 0 ? global.TrimEnd('\n') + "\n" : "\n") + ScriptMarker + code;
            if (!body.EndsWith("\n", StringComparison.Ordinal)) body += "\n";
            File.WriteAllText(Path.Combine(dir, name + ".hmi.js"), body, utf8);
            File.WriteAllText(Path.Combine(dir, name + ".hmi.yml"), "#Version: 2.0\n\nScriptModules:\n  " + name + ":\n    ScriptFile: " + name + ".hmi.js\n", utf8);
            bool ok;
            try
            {
                ok = sw.Scripts.Import(new DirectoryInfo(dir), name);
            }
            catch (Exception ex)
            {
                throw new ToolException("TIA lehnt das Skriptmodul ab: " + UnifiedProps.Innermost(ex));
            }
            if (!ok) throw new ToolException("TIA hat das Skriptmodul nicht importiert. Dateien: " + dir);
        }

        // ---------- hmi_undo ----------

        public bool Handles(string art)
        {
            return art == "textliste_loeschen" || art == "textliste_zurueck" || art == "skript_zurueck";
        }

        public void Revert(HmiSoftware sw, Dictionary<string, object> step)
        {
            switch ((string)step["art"])
            {
                case "textliste_loeschen":
                    {
                        HmiTextList t = sw.HmiTextLists.Find((string)step["name"]);
                        if (t != null) t.Delete();
                        break;
                    }
                case "textliste_zurueck":
                    sw.HmiTextLists.Import(new DirectoryInfo((string)step["verzeichnis"]), (string)step["datei"]);
                    break;
                case "skript_zurueck":
                    {
                        string name = (string)step["modul"];
                        string dir = step["verzeichnis"] as string;
                        if (dir != null) sw.Scripts.Import(new DirectoryInfo(dir), name);
                        else ImportScript(sw, name, "", "");
                        break;
                    }
            }
        }
    }
